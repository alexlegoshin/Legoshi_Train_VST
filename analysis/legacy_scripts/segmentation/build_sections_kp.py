def build():
    rows = []
    for start, end, section, desc, hint in ROWS:
        rows.append(dict(
            song="основной трек",
            start_s=parse_timecode(start), end_s=parse_timecode(end),
            section=section, description=desc,
            hierarchy_hint_DRAFT_NOT_CONFIRMED=hint,
        ))
    df = pd.DataFrame(rows)
    out = ROOT / "_analysis" / "sections.csv"
    df.to_csv(out, index=False, encoding="utf-8-sig")
    print(f"sections.csv: {len(df)} разделов -> {out}")
    print(df[["start_s", "end_s", "section"]].to_string(index=False))
    return df


if __name__ == "__main__":
    build()
